# Define a class
class Car:
    def __init__(self, brand, model):
        self.brand = brand
        self.model = model
    
    def display_info(self):
        print(f"Car: {self.brand} {self.model}")

# Create an object of the class
my_car = Car("BMW", "M4")

# Call the method
my_car.display_info()
